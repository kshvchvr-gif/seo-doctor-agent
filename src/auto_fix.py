"""
Phase 3 — open a reviewable PR against the website repo with the planned fixes.

Safety model:
  * NEVER pushes to the site's main branch. A new branch is created and a
    (draft) PR is opened; a human reviews and merges.
  * If SITE_REPO_TOKEN is missing, it prints setup instructions and exits 0
    (a skipped run must not fail CI).
  * Idempotent-ish: existing open autofix branches/PRs are reused instead of
    spamming a new one every run.
  * Every applied change is recorded in fixes_history.json.

Env:
  SITE_REPO       e.g. "kshvchvr-gif/krishnbhakti-web" (default set below)
  SITE_REPO_TOKEN fine-grained PAT with contents:write + pull_requests:write
  FIX_PLAN_PATH   default reports/fix_plan.json
  BASE_BRANCH     default "main"
  AUTOFIX_DRAFT   default "1" (open as draft PR)
"""
import json
import os
import subprocess
import sys
import tempfile
import datetime
import requests

from . import fixes

SITE_REPO = os.environ.get("SITE_REPO", "kshvchvr-gif/krishnbhakti-web")
SITE_OWNER = SITE_REPO.split("/")[0]
BASE_BRANCH = os.environ.get("BASE_BRANCH", "main")
BRANCH = os.environ.get("AUTOFIX_BRANCH", "seo-autofix")  # stable rolling branch
DRAFT = os.environ.get("AUTOFIX_DRAFT", "1") not in ("0", "false", "False")
API = "https://api.github.com"
REPO_ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
FIX_PLAN_PATH = os.environ.get("FIX_PLAN_PATH", os.path.join(REPO_ROOT, "reports", "fix_plan.json"))
HISTORY_PATH = os.path.join(REPO_ROOT, "fixes_history.json")
LABEL = "seo-autofix"


def _token() -> str:
    return os.environ.get("SITE_REPO_TOKEN") or os.environ.get("GH_TOKEN") or ""


def _api_headers(token):
    return {
        "Authorization": f"Bearer {token}",
        "Accept": "application/vnd.github+json",
        "X-GitHub-Api-Version": "2022-11-28",
    }


def _run(cmd, cwd=None, check=True):
    return subprocess.run(cmd, cwd=cwd, check=check, capture_output=True, text=True)


def clone_site(dest: str, token: str):
    url = f"https://x-access-token:{token}@github.com/{SITE_REPO}.git"
    _run(["git", "clone", "--depth", "1", "--branch", BASE_BRANCH, url, dest])
    return url


def _find_existing_pr(token: str):
    """Reuse the open rolling autofix PR if one exists (avoid PR-per-run spam)."""
    r = requests.get(f"{API}/repos/{SITE_REPO}/pulls",
                     headers=_api_headers(token),
                     params={"state": "open", "head": f"{SITE_OWNER}:{BRANCH}"}, timeout=30)
    if r.status_code == 200 and r.json():
        return r.json()[0]
    return None


def open_pr(token: str, branch: str, title: str, body: str):
    payload = {"title": title, "head": branch, "base": BASE_BRANCH, "body": body, "draft": DRAFT}
    r = requests.post(f"{API}/repos/{SITE_REPO}/pulls",
                      headers=_api_headers(token), json=payload, timeout=60)
    if r.status_code not in (200, 201):
        raise RuntimeError(f"PR create failed ({r.status_code}): {r.text[:300]}")
    return r.json()


def update_pr_body(token: str, number: int, body: str):
    """Refresh a reused rolling PR's description so it matches the branch contents."""
    r = requests.patch(f"{API}/repos/{SITE_REPO}/pulls/{number}",
                       headers=_api_headers(token), json={"body": body}, timeout=60)
    return r.status_code in (200, 201)



def _load_plan() -> dict:
    with open(FIX_PLAN_PATH, "r", encoding="utf-8") as f:
        return json.load(f)


def _pr_body(applied, skipped) -> str:
    lines = ["## 🤖 SEO Doctor — safe on-page fixes (auto-generated)",
             "",
             "> Low-risk changes only (title, meta description, canonical, image alt).",
             "> Please review before merging. Nothing here touches main directly.",
             ""]
    by_file = {}
    for a in applied:
        by_file.setdefault(a["file"], []).append(a)
    lines.append(f"**Files changed:** {len(by_file)} · **Fixes applied:** {sum(len(v) for v in by_file.values())}")
    lines.append("")
    for file, items in list(by_file.items())[:30]:
        lines.append(f"### `{file}`")
        for a in items:
            for c in a["changes"]:
                old = (c.get("old") or "").strip().replace("\n", " ")
                new = (c.get("new") or "").strip().replace("\n", " ")
                lines.append(f"- **{c['type']}**")
                if old:
                    lines.append(f"  - from: `{old[:160]}`")
                lines.append(f"  - to: `{new[:160]}`")
        lines.append("")
    if skipped:
        lines.append(f"<details><summary>Skipped {len(skipped)} (no change / anchor not found)</summary>")
        lines.append("")
        for s in skipped[:50]:
            lines.append(f"- `{s.get('file','')}` — {s.get('skip_reason','')}")
        lines.append("</details>")
    lines += ["", "---", "_Generated by seo-doctor-agent Phase 3. Review the diff, then merge if it looks good._"]
    return "\n".join(lines)


def _merge_fixes(prev_fixes, new_fixes):
    """Union change records keyed by (file, change type); the newest description wins.

    The auto-fix branch is a *rolling* branch, so later runs see already-applied
    changes as no-ops and report only their delta. Merging keeps one accurate
    record of everything the PR now contains.
    """
    urls, changes, order = {}, {}, []
    for fx in list(prev_fixes or []) + list(new_fixes or []):
        f = fx.get("file")
        if fx.get("url"):
            urls[f] = fx["url"]
        else:
            urls.setdefault(f, "")
        for c in fx.get("changes", []):
            key = (f, c.get("type"))
            if key not in changes:
                order.append(key)
            changes[key] = c
    by_file = {}
    for key in order:
        f, _t = key
        by_file.setdefault(f, {"file": f, "url": urls.get(f, ""), "changes": []})
    for key in order:
        f, _t = key
        by_file[f]["changes"].append(changes[key])
    return [by_file[f] for f in sorted(by_file)]



def _record_history(branch, pr, result, plan):
    history = []
    if os.path.exists(HISTORY_PATH):
        with open(HISTORY_PATH, "r", encoding="utf-8") as f:
            try:
                loaded = json.load(f)
                history = loaded if isinstance(loaded, list) else []
            except (ValueError, TypeError):
                # Never let an empty/corrupt history file fail the fixer run.
                history = []
    prn = pr.get("number")
    new_fixes = [{"file": a["file"], "url": a.get("url", ""), "changes": a["changes"]}
                 for a in result["applied"]]
    new_pages = sorted({a["url"] for a in result["applied"] if a.get("url")})

    # The branch (and therefore the PR) is rolling: collapse any previous entries
    # for this same PR into one cumulative record instead of appending duplicates.
    prev = {"pages": [], "files": [], "fixes": []}
    for h in history:
        if h.get("pr") == prn and h.get("branch") == branch:
            prev["pages"] = sorted(set(prev["pages"]) | set(h.get("pages") or []))
            prev["files"] = sorted(set(prev["files"]) | set(h.get("files") or []))
            prev["fixes"] = _merge_fixes(prev["fixes"], h.get("fixes"))
    history = [h for h in history if not (h.get("pr") == prn and h.get("branch") == branch)]

    entry = {
        "date": datetime.date.today().isoformat(),
        "pr": prn,
        "url": pr.get("html_url"),
        "branch": branch,
        "status": "open",
        "pages": sorted(set(prev["pages"]) | set(new_pages)),
        "files": sorted(set(prev["files"]) | set(result["files_changed"])),
        "fixes": _merge_fixes(prev["fixes"], new_fixes),
        "direction": "pending",   # improved / worse / flat, filled by verify_fixes
    }
    history.append(entry)
    with open(HISTORY_PATH, "w", encoding="utf-8") as f:
        json.dump(history, f, indent=2, ensure_ascii=False)
    return entry



def run(dry_run: bool = False) -> int:
    token = _token()
    if not token:
        print("SITE_REPO_TOKEN not set — skipping auto-fix.")
        print("Add a fine-grained PAT (contents:write + pull_requests:write on "
              f"{SITE_REPO}) as the repo secret SITE_REPO_TOKEN to enable Phase 3.")
        return 0

    if not os.path.exists(FIX_PLAN_PATH):
        print(f"No fix plan at {FIX_PLAN_PATH} — nothing to do.")
        return 0
    plan = _load_plan()
    if not plan.get("fixes"):
        print("Fix plan is empty — nothing to do.")
        return 0

    existing = _find_existing_pr(token)

    workdir = tempfile.mkdtemp(prefix="site-")
    site_root = os.path.join(workdir, "site")
    print(f"Cloning {SITE_REPO}@{BASE_BRANCH} ...")
    clone_site(site_root, token)

    # Base the rolling branch on its remote tip if it already exists, so the
    # new commit fast-forwards (no force-push, no lost review comments).
    fetched = _run(["git", "fetch", "--depth", "1", "origin", BRANCH], cwd=site_root, check=False)
    reused = fetched.returncode == 0
    if reused:
        print(f"Reusing existing branch {BRANCH}")
        _run(["git", "checkout", "-B", BRANCH, "FETCH_HEAD"], cwd=site_root)
    else:
        _run(["git", "checkout", "-b", BRANCH], cwd=site_root)

    result = fixes.apply_plan(site_root, plan)
    print(f"Applied {sum(len(a['changes']) for a in result['applied'])} changes "
          f"across {len(result['files_changed'])} files; skipped {len(result['skipped'])}.")
    if not result["applied"]:
        print("Nothing new applied this run (rolling branch already up to date).")

    if dry_run:
        print("DRY RUN — not committing/pushing. Changed files:")
        for fl in result["files_changed"]:
            print("  ", fl)
        return 0

    if result["applied"]:
        # commit + push to the rolling branch (never main)
        _run(["git", "config", "user.name", "seo-doctor-bot"], cwd=site_root)
        _run(["git", "config", "user.email", "actions@github.com"], cwd=site_root)
        _run(["git", "add", "-A"], cwd=site_root)
        _run(["git", "commit", "-m", f"SEO auto-fix {datetime.date.today().isoformat()}: "
                                     f"{len(result['files_changed'])} file(s)"], cwd=site_root)
        push = _run(["git", "push", "origin", BRANCH], cwd=site_root, check=False)
        if push.returncode != 0:
            print("Plain push rejected, retrying with --force-with-lease ...")
            _run(["git", "push", "origin", BRANCH, "--force-with-lease"], cwd=site_root)
    else:
        print("Skipping commit/push — branch unchanged.")

    # Only reuse the existing PR if we actually based on its branch.
    pr = existing if reused else None
    if not pr:
        if not result["applied"]:
            print("No existing PR and nothing to open one for — exit.")
            return 0
        title = f"SEO auto-fix — {datetime.date.today().isoformat()}"
        pr = open_pr(token, BRANCH, title, _pr_body(result["applied"], result["skipped"]))
        print(f"Opened PR #{pr['number']}: {pr['html_url']}")
        try:  # best-effort label
            requests.post(f"{API}/repos/{SITE_REPO}/issues/{pr['number']}/labels",
                          headers=_api_headers(token), json={"labels": [LABEL]}, timeout=30)
        except requests.RequestException:
            pass
    else:
        print(f"Updated existing PR #{pr['number']}: {pr['html_url']}")

    # One cumulative entry per rolling PR (also collapses earlier duplicate rows).
    entry = _record_history(BRANCH, pr, result, plan)
    print(f"Recorded in fixes_history.json (status={entry['status']}).")

    if existing is not None:
        # Rolling branch: push the refreshed, cumulative description to the PR.
        if update_pr_body(token, pr["number"], _pr_body(entry["fixes"], result["skipped"])):
            print(f"Refreshed PR #{pr['number']} description ({len(entry['fixes'])} file(s)).")
    return 0


if __name__ == "__main__":
    sys.exit(run(dry_run="--dry-run" in sys.argv))
